def read(p):
    with open(p, encoding='utf-8', newline='') as h: return h.read()
def write(p, s):
    with open(p, 'w', encoding='utf-8', newline='') as h: h.write(s)

errors = []
def edit(path, pairs, done_marker, optional=False):
    if not os.path.exists(path):
        errors.append('missing file: ' + path); return
    s = read(path)
    if done_marker in s:
        print('already applied:', path); return
    nl = '\r\n' if '\r\n' in s else '\n'
    changed = False
    for old, new in pairs:
        old = old.replace('\n', nl); new = new.replace('\n', nl)
        if old not in s:
            if optional: continue
            errors.append('pattern not found in %s: %r' % (path, old[:60])); return
        s = s.replace(old, new, 1); changed = True
    if changed or not optional: write(path, s); print('edited:', path)
    else: print('already applied:', path)

